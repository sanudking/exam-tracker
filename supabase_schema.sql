-- Run this in your Supabase SQL Editor to support the new features

-- 1. Add new columns to the exams table
ALTER TABLE exams ADD COLUMN IF NOT EXISTS grade TEXT;
ALTER TABLE exams ADD COLUMN IF NOT EXISTS target_grade TEXT;
ALTER TABLE exams ADD COLUMN IF NOT EXISTS credits REAL;

-- 2. Create the milestones table
CREATE TABLE IF NOT EXISTS milestones (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  exam_id BIGINT NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  is_completed BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Note: RLS (Row Level Security) for milestones
ALTER TABLE milestones ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can manage their own milestones"
  ON milestones FOR ALL
  USING (auth.uid() = user_id);

-- 3. Create the study_sessions table
CREATE TABLE IF NOT EXISTS study_sessions (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  exam_id BIGINT NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
  start_time TIMESTAMPTZ NOT NULL,
  duration_minutes INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Note: RLS (Row Level Security) for study_sessions
ALTER TABLE study_sessions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can manage their own study sessions"
  ON study_sessions FOR ALL
  USING (auth.uid() = user_id);
